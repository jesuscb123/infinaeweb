          <section class="legal-section" id="s2">
            <div class="legal-section-head"><span class="legal-num">02</span><h2>Principios aplicados en el tratamiento de datos</h2></div>
            <p>En el tratamiento de sus datos personales, Infinae aplicará los siguientes principios conforme al RGPD:</p>
            <ul>
              <li><strong>Licitud, lealtad y transparencia:</strong> Infinae requerirá el consentimiento para el tratamiento de los datos personales, informando a la persona usuaria con absoluta transparencia sobre los fines específicos.</li>
              <li><strong>Minimización de datos:</strong> solo se solicitarán los datos estrictamente necesarios para los fines declarados.</li>
              <li><strong>Limitación del plazo de conservación:</strong> los datos se mantendrán durante el tiempo estrictamente necesario para el fin del tratamiento, o durante los plazos legalmente exigibles.</li>
              <li><strong>Integridad y confidencialidad:</strong> los datos personales serán tratados garantizando su seguridad, confidencialidad e integridad, adoptando las medidas técnicas y organizativas necesarias.</li>
            </ul>
          </section>

          <section class="legal-section" id="s3">
            <div class="legal-section-head"><span class="legal-num">03</span><h2>Obtención de datos personales</h2></div>
            <p>Para navegar por el sitio web no es necesario facilitar ningún dato personal. Los casos en los que usted proporciona sus datos personales son los siguientes:</p>
            <ul>
              <li>Al cumplimentar el <strong>formulario de contacto</strong> para plantear una consulta o solicitud de colaboración empresarial.</li>
              <li>Al comunicarse con el equipo de Infinae a través del correo electrónico o el teléfono facilitados en el sitio web.</li>
            </ul>
          </section>

          <section class="legal-section" id="s4">
            <div class="legal-section-head"><span class="legal-num">04</span><h2>Finalidad del tratamiento de datos personales</h2></div>
            <p>Los datos personales que facilite a Infinae serán tratados con las siguientes finalidades:</p>
            <ul>
              <li><strong>Atender solicitudes de contacto:</strong> gestionar y responder consultas enviadas a través del formulario del sitio web o por correo electrónico.</li>
              <li><strong>Gestión comercial:</strong> tramitar solicitudes de colaboración, dar seguimiento a las comunicaciones derivadas del contacto establecido con la empresa interesada.</li>
              <li><strong>Gestión de pagos y facturación:</strong> en su caso, procesar pagos, emitir justificantes y cumplir las obligaciones contables y fiscales legalmente exigibles derivadas de la relación comercial.</li>
              <li><strong>Comunicaciones comerciales:</strong> enviar información sobre los servicios o novedades de Infinae, únicamente cuando la persona usuaria haya prestado su consentimiento expreso.</li>
              <li><strong>Mejora del servicio web:</strong> analizar de forma anónima y agregada el uso del sitio para mejorar su funcionamiento y contenidos.</li>
            </ul>
          </section>

          <section class="legal-section" id="s5">
            <div class="legal-section-head"><span class="legal-num">05</span><h2>Legitimación para el tratamiento</h2></div>
            <p>La base legal para el tratamiento de sus datos es:</p>
            <ul>
              <li><strong>Consentimiento del interesado</strong> para la atención de consultas y el envío de comunicaciones comerciales.</li>
              <li><strong>Ejecución de un contrato o precontrato</strong> para la gestión de la relación comercial con la empresa contactada.</li>
              <li><strong>Obligación legal</strong> para el cumplimiento de obligaciones fiscales, contables y administrativas.</li>
            </ul>
          </section>

          <section class="legal-section" id="s6">
            <div class="legal-section-head"><span class="legal-num">06</span><h2>Categorías de datos personales</h2></div>
            <p>Las categorías de datos personales que trata Infinae son <strong>datos identificativos</strong> (nombre, correo electrónico) y, cuando corresponda, <strong>datos de la empresa</strong> (nombre comercial) y el contenido del mensaje facilitado a través del formulario de contacto. No se tratan categorías de datos especialmente protegidos.</p>
          </section>

          <section class="legal-section" id="s7">
            <div class="legal-section-head"><span class="legal-num">07</span><h2>Conservación de datos personales</h2></div>
            <p>Los datos personales se conservarán durante el tiempo estrictamente necesario para las finalidades declaradas:</p>
            <ul>
              <li>Consultas de contacto: durante la gestión de la consulta y los plazos razonables para atender posibles responsabilidades.</li>
              <li>Relación comercial: durante la relación con la empresa y los plazos legales aplicables.</li>
              <li>Obligaciones contables y fiscales, en su caso: durante los plazos legalmente exigibles (mínimo 5 años).</li>
              <li>Comunicaciones comerciales: hasta la retirada del consentimiento o la solicitud de baja.</li>
            </ul>
            <p>Transcurrido el plazo de conservación, los datos serán bloqueados o suprimidos de forma segura.</p>
          </section>

          <section class="legal-section" id="s8">
            <div class="legal-section-head"><span class="legal-num">08</span><h2>Destinatarios de datos personales</h2></div>
            <p>Infinae informa de que sus datos personales no serán cedidos a terceros, salvo en los siguientes supuestos:</p>
            <ul>
              <li>Cuando exista una <strong>obligación legal</strong> que así lo requiera (autoridades fiscales, administrativas o judiciales).</li>
              <li>A <strong>proveedores de servicios tecnológicos</strong> que actúen como encargados del tratamiento bajo contrato (alojamiento web, servicios de correo electrónico), garantizando en todo caso el cumplimiento del RGPD.</li>
            </ul>
            <p>En ningún caso se cederán datos a terceros con fines comerciales propios sin el consentimiento expreso de la persona usuaria.</p>
