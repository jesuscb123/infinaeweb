          <section class="legal-section" id="s2">
            <div class="legal-section-head"><span class="legal-num">02</span><h2>Principios aplicados en el tratamiento de datos</h2></div>
            <p>En el tratamiento de sus datos personales, Infinae aplicará los siguientes principios conforme al RGPD:</p>
            <ul>
              <li><strong>Licitud, lealtad y transparencia:</strong> Infinae requerirá el consentimiento para el tratamiento de los datos personales, informando a la persona usuaria con absoluta transparencia sobre los fines específicos.</li>
              <li><strong>Minimización de datos:</strong> solo se solicitarán los datos estrictamente necesarios para los fines declarados.</li>
              <li><strong>Limitación del plazo de conservación:</strong> los datos se mantendrán durante el tiempo estrictamente necesario para el fin del tratamiento, o durante los plazos legalmente exigibles.</li>
              <li><strong>Integridad y confidencialidad:</strong> los datos personales serán tratados garantizando su seguridad, confidencialidad e integridad, adoptando las medidas técnicas y organizativas necesarias.</li>
            </ul>
          </section>

          <section class="legal-section" id="s3">
            <div class="legal-section-head"><span class="legal-num">03</span><h2>Obtención de datos personales</h2></div>
            <p>Para navegar por el sitio web no es necesario facilitar ningún dato personal. Los casos en los que usted proporciona sus datos personales son los siguientes:</p>
            <ul>
              <li>Al cumplimentar el <strong>formulario de contacto</strong> para plantear una consulta o solicitud de colaboración empresarial.</li>
              <li>Al comunicarse con el equipo de Infinae a través del correo electrónico o el teléfono facilitados en el sitio web.</li>
            </ul>
          </section>

