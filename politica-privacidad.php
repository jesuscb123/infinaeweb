            <p>La base legal para el tratamiento de sus datos es:</p>
            <ul>
              <li><strong>Consentimiento del interesado</strong> para la atención de consultas y el envío de comunicaciones comerciales.</li>
              <li><strong>Ejecución de un contrato o precontrato</strong> para la gestión de la relación comercial con la empresa contactada.</li>
              <li><strong>Obligación legal</strong> para el cumplimiento de obligaciones fiscales, contables y administrativas.</li>
            </ul>
          </section>

          <section class="legal-section" id="s6">
            <div class="legal-section-head"><span class="legal-num">06</span><h2>Categorías de datos personales</h2></div>
            <p>Las categorías de datos personales que trata Infinae son <strong>datos identificativos</strong> (nombre, correo electrónico) y, cuando corresponda, <strong>datos de la empresa</strong> (nombre comercial) y el contenido del mensaje facilitado a través del formulario de contacto. No se tratan categorías de datos especialmente protegidos.</p>
          </section>

          <section class="legal-section" id="s7">
            <div class="legal-section-head"><span class="legal-num">07</span><h2>Conservación de datos personales</h2></div>
            <p>Los datos personales se conservarán durante el tiempo estrictamente necesario para las finalidades declaradas:</p>
            <ul>
              <li>Consultas de contacto: durante la gestión de la consulta y los plazos razonables para atender posibles responsabilidades.</li>
              <li>Relación comercial: durante la relación con la empresa y los plazos legales aplicables.</li>
              <li>Obligaciones contables y fiscales, en su caso: durante los plazos legalmente exigibles (mínimo 5 años).</li>
              <li>Comunicaciones comerciales: hasta la retirada del consentimiento o la solicitud de baja.</li>
            </ul>
            <p>Transcurrido el plazo de conservación, los datos serán bloqueados o suprimidos de forma segura.</p>
          </section>

          <section class="legal-section" id="s8">
            <div class="legal-section-head"><span class="legal-num">08</span><h2>Destinatarios de datos personales</h2></div>
            <p>Infinae informa de que sus datos personales no serán cedidos a terceros, salvo en los siguientes supuestos:</p>
            <ul>
              <li>Cuando exista una <strong>obligación legal</strong> que así lo requiera (autoridades fiscales, administrativas o judiciales).</li>
              <li>A <strong>proveedores de servicios tecnológicos</strong> que actúen como encargados del tratamiento bajo contrato (alojamiento web, servicios de correo electrónico), garantizando en todo caso el cumplimiento del RGPD.</li>
            </ul>
            <p>En ningún caso se cederán datos a terceros con fines comerciales propios sin el consentimiento expreso de la persona usuaria.</p>
